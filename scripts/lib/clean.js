/**
 * 清洗诊断或手术操作名称
 * @param {string} rawName 原始主表行名称
 * @returns {string} 清洗后的名称
 */
function cleanDiagnosisOrOpName(rawName) {
  let s = (rawName || '').trim();
  let prev;
  do {
    prev = s;
    s = s.replace(/[\(（](?:[^\)）]*(?:科|病房|门诊|医院|中心)|儿牙|综合)[\)）]\s*$/g, '');
    s = s.replace(/[\(（](?:\d+|单位|例|次|名)[\)）]\s*$/g, '');
  } while (s !== prev);
  return s.trim();
}

